EXPLAIN (
	ANALYZE,
	BUFFERS,
	VERBOSE
)
WITH
	COURSEPASSCOUNTS AS (
		SELECT
			C.COURSEID,
			C.NAME,
			COUNT(DISTINCT SP.STUDENTID) AS PASSEDSTUDENTS
		FROM
			COURSE C
			JOIN STUDENTPERFORMANCE SP ON C.COURSEID = SP.COURSEID
		WHERE
			SP.MARKS >= 3
		GROUP BY
			C.COURSEID,
			C.NAME
	)
SELECT
	*
FROM
	COURSEPASSCOUNTS
WHERE
	PASSEDSTUDENTS = (
		SELECT
			MAX(PASSEDSTUDENTS)
		FROM
			COURSEPASSCOUNTS
	);
-- 41. Выбрать курс, который сдало наибольшее количество человек.
EXPLAIN (
	ANALYZE,
	BUFFERS,
	VERBOSE
)
SELECT
	C.COURSEID,
	C.NAME,
	COUNT(DISTINCT SP.STUDENTID) AS PASS_STUDENT
FROM
	COURSE C
	JOIN STUDENTPERFORMANCE SP ON C.COURSEID = SP.COURSEID
WHERE
	SP.MARKS >= 3
GROUP BY
	C.COURSEID,
	C.NAME
ORDER BY
	PASS_STUDENT DESC;


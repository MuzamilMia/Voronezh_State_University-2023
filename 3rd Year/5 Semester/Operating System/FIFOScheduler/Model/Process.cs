
/*Планирование FIFO. Планировщик генерирует новые потоки и запускает существующие и прерывает
 *потоки, квант выполнения которых истек. Выбор потока на выполнение происходит по 
 *заданному алгоритму. При создании потока генерируются его время жизни. При выполнении 
 *потока происходит в случайные моменты времени блокировка. В этом случае поток ставится 
 *в очередь заблокированных и будет находиться там пока планировщик не переведет его в
 *очередь готовых. На форме отображается состояние системы: очередь готовых, очередь 
 *заблокированных, выполняющийся поток*/

using System;
using System.Threading;

namespace FifoScheduler.Model
{
    public class Process
    {
        /// Уникальный идентификатор процесса
        /// Генерируется автоматически при создании
        public int Id { get; set; }
        /// Имя процесса для отображения (P1, P2, P3...)
        public string Name { get; set; }
        /// Остаток времени жизни процесса (в тиках)
        public int LifetimeRemaining { get; set; }

        /// Текущее состояние процесса в планировщике
        public ProcessState State { get; set; } = ProcessState.Ready;

        /// Планировщик автоматически переводит в Ready по истечении
        public DateTime? BlockedUntil { get; set; }

        /// Момент создания процесса
        /// Для статистики и отладки
        public DateTime CreatedAt { get; set; } = DateTime.Now;

        /// Управляется планировщиком FIFO
        public bool HasCpu { get; set; } = false; // Планировщик дает CPU
    }

    /// Состояния процесса в планировщике задач ОС
    public enum ProcessState
    {
        Ready,
        Running,
        Blocked,
        Finished
    }
}

% Основной предикат для генерации всех размещений с повторениями
% generate_placements(N, K, Result)
% N - количество элементов (обычно от 1 до N)
% K - длина размещения
% Result - результирующее размещение (список длины K)

generate_placements(N, K, Result) :-
    % Проверяем, что N и K - натуральные числа
    integer(N), N > 0,
    integer(K), K >= 0,
    % Создаем список длины K
    length(Result, K),
    % Заполняем список числами от 1 до N
    fill(Result, N).

% Заполнение списка элементами
fill([], _).  % Базовый случай: пустой список
fill([X|Xs], N) :-
    % X должен быть числом от 1 до N
    between(1, N, X),
    % Рекурсивно заполняем остаток списка
    fill(Xs, N).


